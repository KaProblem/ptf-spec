// Bundles the server into dist/ptf-mcp.mjs: one file, no npm install needed to run it.
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const read = (rel) => readFileSync(new URL(rel, import.meta.url), "utf8");
const player = read("./src/player.html").replace("/*PTF_HOST_RUNTIME*/", () => read("../runtime/ptf-host.js"));
const tutor = read("./skills/ptf-tutor/SKILL.md").replace(/^---\n[\s\S]*?\n---\n/, "").trim();
const version = JSON.parse(read("./package.json")).version;

await build({
  entryPoints: ["src/server.mjs"],
  outfile: "dist/ptf-mcp.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  legalComments: "none",
  minify: true,
  banner: { js: "// ptf-mcp: generated by build.mjs from src/, do not edit.\nimport { createRequire as __ptfCreateRequire } from 'node:module'; const require = __ptfCreateRequire(import.meta.url);" },
  plugins: [{
    name: "inline-assets",
    setup(b) {
      b.onResolve({ filter: /\/assets\.mjs$/ }, (args) => ({ path: args.path, namespace: "ptf-assets" }));
      b.onLoad({ filter: /.*/, namespace: "ptf-assets" }, () => ({
        contents: `export const PLAYER_HTML = ${JSON.stringify(player)};\nexport const TUTOR_GUIDE = ${JSON.stringify(tutor)};\nexport const VERSION = ${JSON.stringify(version)};\n`,
        loader: "js",
      }));
    },
  }],
});
console.log("wrote dist/ptf-mcp.mjs");
